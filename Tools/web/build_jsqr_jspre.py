"""Embeds jsQR (Apache-2.0, https://github.com/cozmo/jsQR) into a WebGL .jspre so the Web Worker can be created
from a Blob without any network request. Usage: python3 Tools/web/build_jsqr_jspre.py path/to/jsQR.js"""
import json
import os
import sys

root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
source = open(sys.argv[1], encoding="utf-8").read()
out = os.path.join(root, "Assets", "Plugins", "WebGL", "SpookyJsQR.jspre")
with open(out, "w", encoding="utf-8") as f:
    f.write("// jsQR 1.4.0 by Cosmo Wolfe, Apache License 2.0 (see jsQR-LICENSE.txt). Generated by Tools/web/build_jsqr_jspre.py.\n")
    f.write("var SPOOKY_JSQR_SOURCE = " + json.dumps(source) + ";\n")
print("wrote", out, len(source), "chars")
